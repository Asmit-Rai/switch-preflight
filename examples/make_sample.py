def fake_github_token() -> str:
    """A GitHub-token-shaped string, assembled at runtime from harmless pieces."""
    body = "A1b2C3d4E5f6G7h8I9" + "j0K1l2M3n4O5p6Q7r8"
    assert len(body) == 36
    return "gh" + "p" + "_" + body


